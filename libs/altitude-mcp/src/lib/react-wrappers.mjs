// The @southleft/al-react surface, DERIVED from the wrappers themselves.
//
// WHY THIS EXISTS. `altitude_get_component` described a custom element and
// stopped there, so an agent building a React app got the tag name and had to
// guess the rest: the exported wrapper name, where to import it from, and —
// the one that is genuinely unguessable — which prop carries which event.
// `@lit/react`'s `createComponent({ events })` map is what turns the custom
// event `onInputChange` into a React prop, and nothing in the CEM records it.
// A model writing `onChange` on `<ALInput>` produces code that compiles, runs,
// and never fires.
//
// WHY IT IS PARSED, NOT TABULATED. A hand-maintained tag -> wrapper table is
// exactly the drift this repo builds gates against: `libs/al-react` is
// generated by plop and grows a component at a time. The wrappers are the
// source of truth for their own API, so this reads them — the same choice
// stories.mjs makes for story titles and registry.mjs (apps/docs) makes for
// which components have a wrapper at all.
//
// WHAT IS PARSED, AND WHY A REGEX IS ENOUGH. Every wrapper is plop output from
// one template: a `createComponent({ react, tagName, elementClass, events })`
// call with a string-literal events map, over an import of the web component
// from `@southleft/al-web-components/components/<dir>`. That shape is asserted
// by the generator, not hoped for. A file that does not match it is SKIPPED and
// named in `skipped[]` rather than half-parsed — a wrong event map is worse
// than a missing one, because a caller cannot tell it is wrong.
//
// Degrades to an empty index when `libs/al-react` is absent (a partial
// checkout, or this package installed standalone). Callers then omit the
// `react` block, which is the honest answer: no wrapper was found.

import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

import { LIBS_DIR, REPO_ROOT } from './paths.mjs';

/** The specifier a consumer imports every wrapper from (the package barrel). */
export const REACT_PACKAGE = '@southleft/al-react';

let cache = null;
let cacheRoot = null;

function wrappersRoot() {
  return join(LIBS_DIR, 'al-react', 'src', 'components');
}

/** An absolute path in this checkout, as the repo-relative POSIX path a reader can cite. */
function relativize(absolute) {
  const root = String(REPO_ROOT).replace(/\\/g, '/');
  const normalized = String(absolute).replace(/\\/g, '/');
  return normalized.startsWith(`${root}/`) ? normalized.slice(root.length + 1) : normalized;
}

/** Every `.tsx` under `dir`, at any depth — `components/Icons/Add/Add.tsx` included. */
function tsxFilesUnder(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...tsxFilesUnder(full));
    else if (entry.name.endsWith('.tsx') && !entry.name.endsWith('.test.tsx')) out.push(full);
  }
  return out;
}

/**
 * `events: { onDialogClose: 'onDialogClose', ... }` -> `[{ prop, event }]`.
 *
 * Ordered as written. The prop and the event name are the same string today
 * for every wrapper in this library, and they are still reported as two fields:
 * `createComponent` does not require them to match, the mapping is the whole
 * point of the block, and collapsing them would make a future divergence
 * invisible at exactly the surface that exists to prevent it.
 *
 * Brace-COUNTED rather than matched by a `}`-to-end-of-file regex: `events` is
 * the last key in every wrapper plop emits today, and an anchored regex would
 * quietly start reading the wrong span the day the template puts a key after
 * it. Counting costs three lines and cannot be wrong about where the block ends.
 */
function parseEvents(source) {
  const open = /events:\s*\{/.exec(source);
  if (!open) return [];
  let depth = 1;
  let index = open.index + open[0].length;
  const start = index;
  while (index < source.length && depth > 0) {
    const character = source[index];
    if (character === '{') depth += 1;
    else if (character === '}') depth -= 1;
    index += 1;
  }
  if (depth !== 0) return [];

  const out = [];
  const pair = /([A-Za-z_$][\w$]*)\s*:\s*['"]([^'"]+)['"]/g;
  let match;
  while ((match = pair.exec(source.slice(start, index - 1))) !== null) {
    out.push({ prop: match[1], event: match[2] });
  }
  return out;
}

/**
 * Build (and cache) the element-directory -> wrapper index.
 *
 * Keyed on the component DIRECTORY (`button`, `input`) rather than the tag,
 * because that is the only identifier both sides carry: the wrapper names it in
 * its import specifier, and the CEM names it in `modulePath`. Deriving the tag
 * here would mean re-deriving `al-` + directory, which is a convention, not a
 * fact — `getReactWrapper()` takes the CEM's `modulePath` instead so the tag
 * never has to be guessed.
 */
export function loadReactWrappers() {
  const root = wrappersRoot();
  if (cache && cacheRoot === root) return cache;

  const byDir = new Map();
  const skipped = [];

  for (const file of tsxFilesUnder(root)) {
    const source = readFileSync(file, 'utf8');
    // `index.tsx` re-exports and calls nothing; only the wrapper module itself
    // declares a component. Filtering on the call, not the filename, means a
    // renamed file is still read and a barrel is still skipped.
    if (!source.includes('createComponent(')) continue;
    // Two shapes, both real. Almost every wrapper exports the
    // `createComponent()` result directly. `ALTheme` does not: it keeps the
    // generated component private as `ALThemeBase` and exports a hand-written
    // `React.forwardRef` over it, because the theme host normalises its six
    // axis props. Matching only the first shape reported al-theme as having no
    // React wrapper at all — a wrong answer, not a missing one, since
    // `ALTheme` is the name a consumer imports.
    const exported =
      /export\s+const\s+([A-Za-z_$][\w$]*)\s*=\s*createComponent\s*\(/.exec(source) ??
      /export\s+const\s+(AL[\w$]*)\s*=/.exec(source);
    // The FULL sub-path after `components/`, not its first segment: the icon
    // wrappers import `components/icon/icons/add`, and keying on `icon` alone
    // made 30-odd icon wrappers collide with each other and overwrite the real
    // `al-icon` entry.
    const element =
      /from\s+['"]@southleft\/(?:al|sl)-web-components\/components\/((?:[\w-]+\/)*[\w-]+)['"]/.exec(source);
    if (!exported || !element) {
      skipped.push(relativize(file));
      continue;
    }
    byDir.set(element[1], {
      component: exported[1],
      importPath: REACT_PACKAGE,
      eventProps: parseEvents(source),
      wrapperFile: relativize(file),
    });
  }

  cache = { byDir, skipped, root };
  cacheRoot = root;
  return cache;
}

/**
 * A CEM module path -> the keys `loadReactWrappers()` may have indexed it by.
 *
 * The index is keyed by the specifier the wrapper imports
 * (`@southleft/al-web-components/components/<key>`), and that specifier resolves
 * TWO WAYS in this library:
 *
 *   components/button/button.ts             a directory with a same-named entry
 *                                           -> the wrapper imports `button`
 *   components/icon/icons/close.ts          a bare module in a shared directory
 *                                           -> the wrapper imports `icon/icons/close`
 *
 * Both are real: the 37 icon wrappers use the second form. Returning both
 * candidates, most specific first, is what joins the two sides without either
 * one deriving a tag name — and getting this wrong silently cost every icon
 * component its React block while the al-icon entry still resolved, which is
 * exactly the kind of partial success that reads as working.
 */
function wrapperKeysFor(modulePath) {
  const segments = String(modulePath ?? '').replace(/\\/g, '/').split('/').filter(Boolean);
  const start = segments.indexOf('components');
  const under = segments.slice(start >= 0 ? start + 1 : 0);
  if (!under.length) return [];
  const withoutExtension = [...under.slice(0, -1), under.at(-1).replace(/\.[cm]?[jt]sx?$/, '')];
  const dirs = under.slice(0, -1);
  return [withoutExtension.join('/'), dirs.join('/')].filter(Boolean);
}

/** The wrapper entry for a CEM module path, or null. */
function entryFor(modulePath, byDir) {
  for (const key of wrapperKeysFor(modulePath)) {
    const entry = byDir.get(key);
    if (entry) return entry;
  }
  return null;
}

/**
 * The `react` block for one component, or `null` when no wrapper ships for it.
 *
 * `null` is a real answer here and is returned as one: 69 wrappers cover most
 * but not all of the library, and a brand-layer component has none at all. A
 * caller that omits the field on null is telling the truth; inventing
 * `AL<Pascal>` from the tag would not be.
 */
export function getReactWrapper(modulePath) {
  const { byDir } = loadReactWrappers();
  const entry = entryFor(modulePath, byDir);
  if (!entry) return null;
  return {
    component: entry.component,
    importPath: entry.importPath,
    eventProps: entry.eventProps,
    /**
     * Ready to paste. The wrappers are barrel-exported, so one specifier serves
     * every component and a consumer never deep-imports one.
     */
    importStatement: `import { ${entry.component} } from '${entry.importPath}';`,
    wrapperFile: entry.wrapperFile,
  };
}

/** Tag -> wrapper name, for the markup translator. Built once per index. */
export function wrapperNamesByTag(components) {
  const { byDir } = loadReactWrappers();
  const map = new Map();
  for (const component of components) {
    const entry = entryFor(component.modulePath, byDir);
    if (entry) map.set(component.tag, entry.component);
  }
  return map;
}

/*
 * ---------------------------------------------------------- the JSX twin
 *
 * Translating the serialized web-component markup into the equivalent React
 * wrapper markup. This is a NARROW transform over markup this repo generated
 * itself (apps/docs/src/lib/examples.mjs), not a general HTML->JSX converter,
 * and it refuses rather than guesses:
 *
 *   <al-button variant="x">  ->  <ALButton variant="x">   tag swap
 *   isDisabled               ->  isDisabled               bare boolean is
 *                                                          already valid JSX
 *   class= / for=            ->  className= / htmlFor=    React's two renames
 *
 * REFUSALS, each a named reason rather than a silently wrong snippet:
 *   - `style="..."`   JSX needs an object literal; converting CSS text into one
 *                     is a guess about units and casing.
 *   - `<!-- -->`      not expressible in JSX at all.
 *   - an `al-*` tag with no wrapper — emitting the custom element inside JSX
 *     would work only if the consumer also registered it by hand, which is the
 *     opposite of what the React path is for.
 *
 * A refusal returns null with the reason, and the caller reports the reason.
 */

/** Every distinct tag name used in a markup string. */
function tagsIn(markup) {
  return new Set([...markup.matchAll(/<\/?([a-zA-Z][\w-]*)/g)].map((match) => match[1]));
}

/**
 * The React twin of one example's markup, or `{ code: null, note }`.
 *
 * @param {string} markup serialized web-component markup
 * @param {Map<string,string>} wrapperByTag tag -> exported wrapper name
 */
export function reactTwin(markup, wrapperByTag) {
  if (!markup) return { code: null, note: 'no markup to translate' };
  if (markup.includes('<!--')) {
    return { code: null, note: 'the example contains an HTML comment, which JSX cannot carry' };
  }
  if (/\sstyle=/.test(markup)) {
    return {
      code: null,
      note:
        'the example sets a `style` attribute; JSX requires a style OBJECT, and converting the ' +
        'CSS text into one would be a guess rather than a translation',
    };
  }

  const unwrapped = [...tagsIn(markup)].filter(
    (tag) => tag.includes('-') && !wrapperByTag.has(tag),
  );
  if (unwrapped.length) {
    return {
      code: null,
      note:
        `the example uses ${unwrapped.map((tag) => `<${tag}>`).join(', ')}, which ships no ` +
        '@southleft/al-react wrapper — a React consumer would have to register the custom element by hand',
    };
  }

  let out = markup;
  for (const [tag, component] of wrapperByTag) {
    if (!out.includes(`<${tag}`) && !out.includes(`</${tag}`)) continue;
    out = out
      .replace(new RegExp(`<${tag}(?=[\\s/>])`, 'g'), `<${component}`)
      .replace(new RegExp(`</${tag}>`, 'g'), `</${component}>`);
  }
  // React's two attribute renames. Bounded by the `=` and a preceding space so
  // an attribute merely ENDING in "for" (`aria-labelledby`, `htmlFor`) is untouched.
  out = out.replace(/(\s)class=/g, '$1className=').replace(/(\s)for=/g, '$1htmlFor=');

  const used = [...wrapperByTag]
    .filter(([, component]) => new RegExp(`<${component}[\\s/>]`).test(out))
    .map(([, component]) => component);

  return {
    code: out,
    imports: used.length ? `import { ${[...new Set(used)].sort().join(', ')} } from '${REACT_PACKAGE}';` : null,
    note: null,
  };
}
