// ---------- main ----------

async function build() {
  // Run from the workspace root so `buildPath: 'dist-v5/...'` lands under
  // libs/al-web-components/styles/dist-v5/.
  process.chdir(SD_ROOT);

  // Clean previous v5 output so deletions surface.
  await fs.rm('dist-v5', { recursive: true, force: true });

  const themes = ['light', 'dark'];
  const brands = [
    { theme: 'dark', brand: 'southleft' },
    { theme: 'light', brand: 'northright' },
    { theme: 'dark', brand: 'northright' },
    { theme: 'dark', brand: 'odyssey' },
  ];

  // Per-theme css + scss tokens files. v3 emits variables.scss + tokens.json
  // from each theme build to the same path, so the *last* build wins. v3
  // order is light → dark, so dark is the surviving copy on disk. Match that.
  for (const theme of themes) {
    const sd = new StyleDictionary(themeConfig(theme, { withCore: theme === 'dark' }));
    await sd.buildAllPlatforms();
  }

  // Per-brand css + scss tokens files.
  for (const { theme, brand } of brands) {
    const sd = new StyleDictionary(brandConfig(theme, brand));
    await sd.buildAllPlatforms();
  }

  console.log('[tokens:v5] build complete → libs/al-web-components/styles/dist-v5/');
}

build().catch((err) => {
  console.error('[tokens:v5] FAIL:', err);
  process.exit(1);
});
