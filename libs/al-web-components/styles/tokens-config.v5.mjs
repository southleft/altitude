// T1.1 — Style Dictionary v5 parallel pipeline.
//
// Runs alongside the v3 pipeline (`tokens-config.js`). Reads DTCG source
// from `styles/tokens-dtcg/` and emits CSS/SCSS/JSON to
// `styles/dist-v5/` so the diff against v3's `styles/dist/` is the
// byte-comparability check the plan demands.
//
// Acceptance (per T1.1):
//   yarn build:tokens:v5 emits CSS whose `--al-*` variable set is
//   byte-identical to v3 output.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';
import { usesReferences, getReferences } from 'style-dictionary/utils';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SD_ROOT = __dirname; // .../libs/al-web-components/styles
const WORKSPACE_ROOT = path.resolve(SD_ROOT, '..'); // .../libs/al-web-components

const themePrefix = 'al';
const themeFontWeightRegular = '400';
const themeFontWeightBold = '600';
const themeFontBaseSize = 16;
const themeSpaceBaseSize = 16;
const themeFontFamilyFallback = 'sans-serif';
const comment = '\n\n/* This file is auto-generated by Style Dictionary. Do not edit directly. */\n';

// ---------- helpers (ported from v3 verbatim) ----------

function formatBoxShadowValue(value) {
  if (Array.isArray(value)) {
    return value
      .map((s) => `${s.x}px ${s.y}px ${s.blur}px ${s.spread}px ${s.color}`)
      .join(', ');
  }
  return `${value.x}px ${value.y}px ${value.blur}px ${value.spread}px ${value.color}`;
}

function formatFontWeightValue(value) {
  return value === 'Bold' ? themeFontWeightBold : themeFontWeightRegular;
}

function formatTypographyValue(value) {
  const fontSize = `${parseFloat(value.fontSize) / themeFontBaseSize}rem`;
  const lineHeight = `${parseFloat(value.lineHeight) / themeFontBaseSize}rem`;
  return `${formatFontWeightValue(value.fontWeight)} ${fontSize}/${lineHeight} ${value.fontFamily}, ${themeFontFamilyFallback}`;
}

function formatSpaceValue(value) {
  return `${parseFloat(value) / themeSpaceBaseSize}rem`;
}

// SD v5 stores DTCG values under `$value` when `usesDtcg: true`. Wrap the
// token access so the rest of the format code can stay structurally close
// to the v3 implementation.
function tokenValue(token) {
  return '$value' in token ? token.$value : token.value;
}
function tokenOriginalValue(token) {
  return '$value' in token.original ? token.original.$value : token.original.value;
}

// ---------- custom transform groups (mirror v3 — no DTCG shorthand transforms) ----------
//
// SD v5's `css`/`scss` groups inject `typography/css/shorthand`,
// `shadow/css/shorthand`, etc. that coerce composite tokens into CSS strings
// BEFORE our format runs. v3 had no such transforms — our custom formatters
// (`formatTypographyValue`, `formatBoxShadowValue`) need the raw value
// objects. Register replacement groups that strip the shorthand transforms.

