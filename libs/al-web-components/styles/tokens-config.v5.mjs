/**
 * The one place a declaration list becomes a CSS rule.
 *
 * `selector` and `layer` are FILE OPTIONS, not literals (R1 of
 * `2026-07-28-scoped-token-emission-brand-wiring`). The defaults —
 * `':root'` and no layer — reproduce the pre-existing output byte for byte,
 * which is the entire back-compat strategy: ten apps, two Storybook previews
 * and ten SCSS files consume the flat `:root` artifacts and none of them had
 * to change.
 */
function renderRule(pairs, { selector = ':root', layer = null } = {}) {
  const indent = layer ? '    ' : '  ';
  const decls = pairs.map(([name, value]) => `${indent}${name}: ${value};`).join('\n');
  if (!layer) return `${selector} {\n${decls}\n}\n`;
  return `@layer ${layer} {\n  ${selector} {\n${decls}\n  }\n}\n`;
}

StyleDictionary.registerFormat({
  name: 'tokens',
  format: ({ dictionary, options }) => {
    const pairs = dictionary.allTokens
      .filter(
        (token) =>
          !token.name.endsWith('-italic') &&
          !token.name.endsWith('-underline') &&
          !token.name.includes('breakpoint')
      )
      .flatMap((token) => {
        let name;
        let value = tokenValue(token);

        if (token.name.includes('font-weight')) {
          name = token.name;
          value = formatFontWeightValue(tokenValue(token));
        } else if (token.name.includes('typography')) {
          name = token.name.endsWith('-regular') ? token.name.replace('-regular', '') : token.name;
          value = formatTypographyValue(tokenValue(token));
        } else if (token.name.includes('box-shadow')) {
          name = token.name;
          value = formatBoxShadowValue(tokenValue(token));
        } else if (!token.name.includes('base') && token.name.includes('space')) {
          name = token.name;
          value = formatSpaceValue(tokenValue(token));
        } else {
          name = token.name;
          value = formatCubicBezierValue(tokenValue(token));
        }

        // Captured so the composite companions below can be emitted as
        // references too, instead of copies of the resolved literal.
        let referenceName = null;
        if (token.name.includes('theme') && options.outputReferences) {
          const origValue = tokenOriginalValue(token);
          if (usesReferences(origValue)) {
            const refs = getReferences(origValue, dictionary.tokens, { usesDtcg: true });
            refs.forEach((ref) => {
              const refName = ref.name.endsWith('-regular') ? ref.name.replace('-regular', '') : ref.name;
              referenceName = refName;
              value = `var(--${themePrefix}-${refName})`;
            });
          }
        }
        const primary = `--${themePrefix}-${name}`;
        return [[primary, value], ...companionsFor(token, primary, referenceName)];
      });

    // R2 — scoped (host) emission is a DELTA, not a copy.
    //
    // `options.onlyNames` (a Set of `--al-…` names) and `options.omitEqualTo`
    // (a Map of `--al-…` -> value read back from an already-emitted `:root`
    // artifact) narrow the declaration list to exactly what the host has to
    // restate. Both are absent for every `:root` file, so those keep emitting
    // the full surface unchanged.
    //
    // Deltas rather than full 17 KB copies because a host INHERITS the base
    // `:root` values through the shadow boundary — restating them costs
    // ~105 KB across the matrix (3.2x the CI bundle allowance) to compute the
    // same thing. See the spec's T9 measurement.
    const only = options.onlyNames ?? null;
    const base = options.omitEqualTo ?? null;
    const kept = pairs.filter(
      ([name, value]) =>
        (!only || only.has(name)) && (!base || base.get(name) !== String(value))
    );

    return comment + renderRule(kept, { selector: options.selector, layer: options.layer });
  },
});

StyleDictionary.registerFormat({
  name: 'al-scss-vars',
  format: ({ dictionary, options }) => {
    const breakpointVariables = dictionary.allTokens
      .filter((token) => token.name.includes('breakpoint'))
      .map((token) => {
        let value = JSON.parse(JSON.stringify(tokenValue(token)));
        const origValue = tokenOriginalValue(token);
        if (options.outputReferences && usesReferences(origValue)) {
          const refs = getReferences(origValue, dictionary.tokens, { usesDtcg: true });
          value = refs.map((ref) => `breakpoint-${ref.name}`).join(', ');
        }
        return `$${themePrefix}-${token.name}: ${value};`;
      })
      .join('\n');

    const themeDeclaration = `$${themePrefix}-theme-prefix: '${themePrefix}';\n`;
    return comment + themeDeclaration + breakpointVariables;
  },
});

StyleDictionary.registerFormat({
  name: 'al-json-flat',
  format: ({ dictionary, options }) => {
    const entries = dictionary.allTokens
      .filter((token) => !token.name.endsWith('-italic') && !token.name.endsWith('-underline'))
      .flatMap((token) => {
        let name;
        let value;
        if (token.name.includes('font-weight')) {
          name = token.name;
          value = formatFontWeightValue(tokenValue(token));
        } else if (token.name.includes('typography')) {
          name = token.name.endsWith('-regular') ? token.name.replace('-regular', '') : token.name;
          value = formatTypographyValue(tokenValue(token));
        } else if (token.name.includes('box-shadow')) {
          name = token.name;
          value = formatBoxShadowValue(tokenValue(token));
        } else {
          name = token.name;
          value = formatCubicBezierValue(tokenValue(token));
        }

        // Captured so the composite companions below can be emitted as
        // references too, instead of copies of the resolved literal.
        let referenceName = null;
        if (token.name.includes('theme') && options.outputReferences) {
          const origValue = tokenOriginalValue(token);
          if (usesReferences(origValue)) {
            const refs = getReferences(origValue, dictionary.tokens, { usesDtcg: true });
            refs.forEach((ref) => {
              const refName = ref.name.endsWith('-regular') ? ref.name.replace('-regular', '') : ref.name;
              referenceName = refName;
              value = `var(--${themePrefix}-${refName})`;
            });
          }
        }
        // companionsFor returns `--al-…` CSS custom-property names; this
        // format keys on the bare `al-…` name, so strip the leading `--`.
        return [
          [`${themePrefix}-${name}`, value],
          ...companionsFor(token, `--${themePrefix}-${name}`, referenceName).map(([n, v]) => [n.slice(2), v]),
        ];
      });

    const variables = entries
      .map(([name, value], index) => `  "${name}": "${value}"${index === entries.length - 1 ? '' : ','}`)
      .join('\n');

    return `{\n${variables}\n}`;
  },
});

