// ---------- scoped `:host` emission (R2) ----------
//
// WHY THIS EXISTS. `<al-theme brand mode density contrast>` has always typed a
// `brand` attribute and `components/theme/theme.scss` has never had a rule
// that reads it, so `brand` was inert while CLAUDE.md, MIGRATION.md and
// `.changeset/v2-major.md` all advertised working multi-brand pages. These
// partials are the missing half.
//
// WHY DELTAS. `:host` blocks are compiled into `<al-theme>`'s `static styles`,
// so their bytes ship in the JS bundle. Restating each brand x mode bundle in
// full costs 104,962 B across the matrix — 3.2x the 33,309 B that CI's
// `baselines-bundle` job allows (`.github/workflows/v2-checks.yml:191-220`).
// A host INHERITS every `--al-*` it does not restate, so the delta computes
// the identical value for ~15 KB. Cost of the choice, stated plainly:
// `<al-theme>` COMPOSES ON TOP of a base token sheet, it does not replace one.
// A page with no `:root` bundle loaded gets brand deltas resolving against
// nothing.
//
// WHY THE BRAND BLOCKS ARE SPLIT IN TWO. `<al-theme>` does not reflect its
// properties, so `<al-theme brand="southleft">` with no `mode` attribute matches
// no `[mode]` selector. Splitting each brand delta into
//   * `:host([brand='x'])`          — the part that is identical in every mode
//                                     the brand builds AND is not a property
//                                     the base theme varies by mode, and
//   * `:host([brand='x'][mode='y'])` — the remainder
// means a brand always contributes its mode-independent identity (type ramp,
// radii, spacing, border weights) even with no `mode` set, and never asserts a
// colour that contradicts the mode actually in force. Measured: southleft
// needs no per-mode block at all today.
//
// SPECIFICITY. `:host([brand][mode])` is exactly 0,3,0 and `:host([brand])` /
// `:host([mode])` are 0,2,0 — the budget `scripts/check-css-layers.js` enforces
// is 0,3,0, so the brand x mode form sits on the ceiling with zero headroom. A
// third attribute is not available; that is why density/contrast stay
// hand-written in theme.scss. The checker lints these generated files directly
// (it used to only read `components/<name>/<name>.scss`, which `@use` hides).

const HOST_DIR = 'dist-v5/scss/host';

/** Parse `--name: value;` out of an emitted artifact. */
async function readDeclarations(file) {
  const text = await fs.readFile(file, 'utf8');
  const map = new Map();
  for (const line of text.split('\n')) {
    const m = line.match(/^\s*(--[A-Za-z0-9-]+):\s*(.*);\s*$/);
    if (m) map.set(m[1], m[2]);
  }
  return map;
}

function hostPlatform(destination, selector, { onlyNames = null, omitEqualTo = null }) {
  return {
    scss: {
      transformGroup: 'scss-v3-shape',
      buildPath: `${HOST_DIR}/`,
      files: [
        {
          destination,
          format: 'tokens',
          options: { outputReferences: true, selector, layer: 'al.theme', onlyNames, omitEqualTo },
        },
      ],
    },
  };
}

// ---------- main ----------

async function build() {
  // Run from the workspace root so `buildPath: 'dist-v5/...'` lands under
  // libs/al-web-components/styles/dist-v5/.
  process.chdir(SD_ROOT);

  // Clean previous v5 output so deletions surface.
  await fs.rm('dist-v5', { recursive: true, force: true });

  const themes = ['light', 'dark'];
  // Which mode `:root` carries in a project bundle. Dark, matching what
  // main.css has baked into `:root` since v3 — changing it would silently
  // repaint every consumer that loads a bundle and sets no mode.
  const DEFAULT_MODE = 'dark';
  const projectBundles = [];
  const brands = [
    // `altitude` is the default brand (`<al-theme brand>` in components/theme/theme.ts).
    // It builds in BOTH modes because the base theme output it used to stand in for
    // exists in both. southleft used to be dark-only ("ink"); spec
    // 2026-08-20-southleft-example-app adds its light "paper" mode — the brand
    // token deltas (colour, radius, border-width, shadow, typography) are
    // theme-independent, so the SAME `tier-2/brand/southleft/*.json` files now
    // build against both base themes.
    { theme: 'light', brand: 'altitude' },
    { theme: 'dark', brand: 'altitude' },
    { theme: 'dark', brand: 'southleft' },
    { theme: 'light', brand: 'southleft' },
  ];

  // Per-theme css + scss tokens files. v3 emits variables.scss + tokens.json
  // from each theme build to the same path, so the *last* build wins. v3
  // order is light → dark, so dark is the surviving copy on disk. Match that.
  for (const theme of themes) {
    const sd = new StyleDictionary(themeConfig(theme, { withCore: theme === 'dark' }));
    await sd.buildAllPlatforms();
  }

  // Per-brand css + scss tokens files.
  for (const { theme, brand } of brands) {
    const sd = new StyleDictionary(brandConfig(theme, brand));
    await sd.buildAllPlatforms();
  }

  // ---- scoped `:host` partials for <al-theme> (R2) ----
  //
  // Derived from the artifacts the two loops above just wrote, so a host block
  // can never disagree with the `:root` block it is a delta of. Emitted last
  // for that reason.

  const themeDecls = Object.fromEntries(
    await Promise.all(
      themes.map(async (t) => [t, await readDeclarations(`dist-v5/css/theme/tokens-${t}.css`)])
    )
  );

  // Properties the BASE theme varies by mode (23 today: the default
  // background/content/border surface, the shadow tint, and the six
  // `--al-box-shadow-N` literals that recompute from it). A brand override of
  // one of these has to live in a `[mode]`-qualified block or it would assert
  // a dark value on a light host.
  const modeVarying = new Set();
  for (const t of themes) {
    for (const [name, value] of themeDecls[t]) {
      if (themes.some((o) => themeDecls[o].get(name) !== value)) modeVarying.add(name);
    }
  }

  const emitted = [];
  async function emitHost(destination, selector, narrowing, theme, brand) {
    const cfg = brand
      ? { include: brandIncludes(theme), source: brandSources(brand, theme) }
      : { source: themeSources(theme) };
    const sd = new StyleDictionary({
      usesDtcg: true,
      log: { verbosity: 'silent', warnings: 'disabled' },
      ...cfg,
      platforms: hostPlatform(destination, selector, narrowing),
    });
    await sd.buildAllPlatforms();
    emitted.push(destination);
  }

  // 1. Mode. Symmetric deltas: each block restates exactly the properties that
  //    differ between the two base themes, so `<al-theme mode="light">` lands
  //    on light values whichever base sheet the page loaded, and
  //    `<al-theme mode="dark">` on a dark page is a no-op restatement.
  //    This replaces the two hardcoded hexes theme.scss used to carry (R4) —
  //    those disagreed with the generated tokens and, sitting on the element,
  //    beat them.
  for (const theme of themes) {
    const other = themes.find((t) => t !== theme);
    await emitHost(
      `tokens-mode-${theme}.scss`,
      `:host([mode='${theme}'])`,
      { omitEqualTo: themeDecls[other] },
      theme,
      null
    );
  }

  // 2. Brand. Split per the header comment. `altitude` is the neutral
  //    reference (`.altitude/BRANDS.md` §6 rule 8) and its bundles are
  //    byte-identical to the base theme, so its delta is empty and no file is
  //    written — an empty rule would be dead weight, and its absence is the
  //    assertion that altitude really is neutral.
  const byBrand = new Map();
  for (const { theme, brand } of brands) {
    if (!byBrand.has(brand)) byBrand.set(brand, []);
    byBrand.get(brand).push(theme);
  }

  /**
   * Every property ANY non-default brand overrides, and in which modes. The
   * default brand needs this to write a RESET block — see the emit below.
   */
  const DEFAULT_BRAND = 'altitude';
  const overriddenByOthers = new Map(); // name -> Set(theme)

  for (const [brand, brandModes] of byBrand) {
    const deltas = new Map();
    for (const theme of brandModes) {
      const bundle = await readDeclarations(`dist-v5/css/brand/tokens-${brand}-${theme}.css`);
      const d = new Map();
      for (const [name, value] of bundle) {
        if (themeDecls[theme].get(name) !== value) d.set(name, value);
      }
      deltas.set(theme, d);
    }
    const allNames = new Set([...deltas.values()].flatMap((d) => [...d.keys()]));
    if (brand !== DEFAULT_BRAND) {
      for (const theme of brandModes) {
        for (const name of deltas.get(theme).keys()) {
          if (!overriddenByOthers.has(name)) overriddenByOthers.set(name, new Set());
          overriddenByOthers.get(name).add(theme);
        }
      }
    }
    const invariant = new Set();
    const perMode = new Set();
    for (const name of allNames) {
      const first = deltas.get(brandModes[0]).get(name);
      const sameInEveryMode = brandModes.every((t) => deltas.get(t).get(name) === first);
      if (sameInEveryMode && !modeVarying.has(name)) invariant.add(name);
      else perMode.add(name);
    }

    if (invariant.size > 0) {
      await emitHost(
        `tokens-brand-${brand}.scss`,
        `:host([brand='${brand}'])`,
        { onlyNames: invariant, omitEqualTo: themeDecls[brandModes[0]] },
        brandModes[0],
        brand
      );
    }
    for (const theme of brandModes) {
      const names = new Set([...perMode].filter((n) => deltas.get(theme).has(n)));
      if (names.size === 0) continue;
      await emitHost(
        `tokens-brand-${brand}-${theme}.scss`,
        `:host([brand='${brand}'][mode='${theme}'])`,
        { onlyNames: names, omitEqualTo: themeDecls[theme] },
        theme,
        brand
      );
    }
  }

  // 2b. THE DEFAULT BRAND'S RESET BLOCK.
  //
  //     `altitude` is the neutral reference, so its delta against the base is
  //     empty and for a long time no file was written for it. That was a real
  //     hole, not an elegance: custom properties INHERIT, so
  //     `<al-theme brand="altitude">` nested inside `<al-theme brand="southleft">`
  //     had nothing to re-declare and simply inherited southleft's values.
  //
  //     It looked fixed on 2026-08-31, but only by accident — the v2 restyle
  //     had moved `background.primary-default` into the MODE partials, which
  //     every host re-declares regardless of brand, so the one property the
  //     probe read happened to reset. `tests`' own note said so plainly: "this
  //     does NOT make empty-delta nesting safe in general: a property that
  //     lives ONLY in a brand partial still inherits through."
  //
  //     2026-09-03 proved it: moving southleft onto the real `color.primary`
  //     and `color.neutral` role ramps put those properties in a brand-only
  //     partial, and the nested-altitude probe went red immediately.
  //
  //     The structural fix is to stop relying on emptiness. For the union of
  //     every property ANY other brand overrides, altitude now restates the
  //     BASE value on its own host. Absence stops being the assertion of
  //     neutrality; an explicit restatement is. It costs one small generated
  //     block and makes nesting work for every property, not the lucky ones.
  if (overriddenByOthers.size > 0) {
    const defaultModes = byBrand.get(DEFAULT_BRAND) ?? themes;
    const resetInvariant = new Set();
    const resetPerMode = new Map(themes.map((t) => [t, new Set()]));
    for (const [name, inThemes] of overriddenByOthers) {
      if (modeVarying.has(name)) {
        for (const t of inThemes) resetPerMode.get(t)?.add(name);
      } else {
        resetInvariant.add(name);
      }
    }

    if (resetInvariant.size > 0) {
      await emitHost(
        `tokens-brand-${DEFAULT_BRAND}.scss`,
        `:host([brand='${DEFAULT_BRAND}'])`,
        { onlyNames: resetInvariant },
        defaultModes[0],
        DEFAULT_BRAND
      );
    }
    for (const theme of themes) {
      const names = resetPerMode.get(theme);
      if (!names || names.size === 0) continue;
      await emitHost(
        `tokens-brand-${DEFAULT_BRAND}-${theme}.scss`,
        `:host([brand='${DEFAULT_BRAND}'][mode='${theme}'])`,
        { onlyNames: names },
        theme,
        DEFAULT_BRAND
      );
    }
  }

  // 3. The entry point `components/theme/theme.scss` @uses. Order matters for
  //    the two 0,2,0 families: mode first, brand second, so that when a brand
  //    and the base theme both name a property the brand wins. (Today they
  //    never collide — `modeVarying` names are routed to the 0,3,0 blocks —
  //    but the ordering makes that a property of the file, not luck.)
  const order = [
    ...emitted.filter((f) => f.startsWith('tokens-mode-')),
    ...emitted.filter((f) => f.startsWith('tokens-brand-') && f.split('-').length === 3),
    ...emitted.filter((f) => f.startsWith('tokens-brand-') && f.split('-').length > 3),
  ];
  await fs.writeFile(
    `${HOST_DIR}/_index.scss`,
    `${comment}// Scoped token blocks for <al-theme>. Generated by styles/tokens-config.v5.mjs.\n` +
      `// Loaded by components/theme/theme.scss; see that file and the emitter's\n` +
      `// "scoped \`:host\` emission" comment for the delta/specificity rationale.\n` +
      order.map((f) => `@use './${f}';`).join('\n') +
      '\n'
  );

  // ---- 4. PER-PROJECT BUNDLES ----
  //
  //     One design system, one stylesheet, both modes — which is exactly how
  //     the Figma side models it: a file IS a system, `Tier 1 | Colors` holds
  //     that system's values, and `Tier 2 | Theme` carries Light and Dark as
  //     two modes of ONE collection. There is no brand dimension there, and
  //     after this there is none here either.
  //
  //     Composed from the artifacts the loops above already wrote, never
  //     re-derived, so a project bundle cannot disagree with the `:root` build
  //     it is made of — the same rule the host partials follow.
  //
  //     Shape, and why:
  //       :root, [data-al-project='<id>']
  //                                the DEFAULT mode in full. Dark at :root,
  //                                because that is what main.css has always
  //                                baked into :root and this must not move the
  //                                default rendering.
  //
  //                                The second selector is what keeps TWO design
  //                                systems able to share a document, which the
  //                                brand axis used to provide and which dropping
  //                                it would otherwise have cost. Load both
  //                                bundles and each subtree marked
  //                                `data-al-project` resolves its own system;
  //                                `:root` belongs to whichever loaded last, so
  //                                a two-system page marks both subtrees
  //                                explicitly rather than relying on order.
  //       [data-al-mode='light']   only the properties that differ by mode.
  //       [data-al-mode='dark']    the same delta, re-asserted, so a dark scope
  //                                nested INSIDE a light one resolves back —
  //                                without it, scoping would only work one way.
  //
  //     Attribute selectors rather than a media query or a class: they match at
  //     ANY depth, so a subtree can carry its own mode, and custom properties
  //     inherit through shadow boundaries from whatever element matched. That is
  //     what keeps scoped theming working once the palette leaves <al-theme>.
  const PROJECT_DIR = 'dist-v5/css/project';
  await fs.mkdir(PROJECT_DIR, { recursive: true });
  const projectNames = [...new Set(brands.map((b) => b.brand))];
  for (const project of projectNames) {
    const perMode = Object.fromEntries(
      await Promise.all(
        themes.map(async (t) => [t, await readDeclarations(`dist-v5/css/brand/tokens-${project}-${t}.css`)])
      )
    );
    const base = perMode[DEFAULT_MODE];
    const modeDelta = (t) =>
      [...perMode[t]].filter(([name, value]) =>
        themes.some((other) => perMode[other].get(name) !== value)
      );

    const parts = [
      `/* ${project} — generated by styles/tokens-config.v5.mjs. Do not edit directly.
` +
        `   One design system, both modes. Set data-al-mode on any element to scope a mode. */
`,
      renderRule([...base], { selector: `:root, [data-al-project='${project}']` }),
    ];
    for (const t of themes) {
      const delta = modeDelta(t);
      if (delta.length) parts.push(renderRule(delta, { selector: `[data-al-mode='${t}']` }));
    }
    await fs.writeFile(`${PROJECT_DIR}/${project}.css`, parts.join('\n'));
    projectBundles.push(`${project}.css (${base.size} base + ${modeDelta('light').length} per mode)`);
  }

  console.log(
    `[tokens:v5] build complete → libs/al-web-components/styles/dist-v5/ ` +
      `(${order.length} scoped host partial(s), ${projectBundles.length} project bundle(s): ${projectBundles.join(', ')})`
  );
}

build().catch((err) => {
  console.error('[tokens:v5] FAIL:', err);
  process.exit(1);
});
