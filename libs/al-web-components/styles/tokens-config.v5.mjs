const themeConfig = (themeName, { withCore = false } = {}) => {
  const scssFiles = [
    {
      destination: `tokens-${themeName}.scss`,
      format: 'tokens',
      options: { outputReferences: true },
    },
  ];
  if (withCore) {
    // Mirror v3: variables.scss is emitted from each theme build,
    // overwriting (output is theme-independent — only breakpoints —
    // so the overwrite is idempotent).
    scssFiles.push({
      destination: '../../core/variables.scss',
      format: 'al-scss-vars',
      options: { outputReferences: true },
    });
  }
  const platforms = {
    css: {
      transformGroup: 'css-v3-shape',
      buildPath: 'dist-v5/css/theme/',
      files: [
        {
          destination: `tokens-${themeName}.css`,
          format: 'tokens',
          options: { outputReferences: true },
        },
      ],
    },
    scss: {
      transformGroup: 'scss-v3-shape',
      buildPath: 'dist-v5/scss/theme/',
      files: scssFiles,
    },
  };
  if (withCore) {
    platforms.json = {
      transformGroup: 'scss-v3-shape',
      buildPath: 'dist-v5/',
      files: [
        {
          destination: 'tokens.json',
          format: 'al-json-flat',
          options: { outputReferences: true },
        },
      ],
    };
  }
  return {
    usesDtcg: true,
    log: { verbosity: 'silent', warnings: 'disabled' },
    source: themeSources(themeName),
    platforms,
  };
};

