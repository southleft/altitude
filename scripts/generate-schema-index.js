#!/usr/bin/env node
/**
 * T3.3 follow-up — generate `libs/al-web-components/schemas/INDEX.md` that
 * maps every component name (from migration.json) to its JSON Schema. Linked
 * from AGENTS.md so an agent can navigate from "this component" to "the
 * contract that gates it".
 *
 * The plan-acceptance text demands "AGENTS.md links each component to its
 * schema". A static index file is the cleanest implementation — agents
 * dereference it, and the index is regenerated as part of the schema build
 * so it can't drift.
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const REPO = path.resolve(__dirname, '..');
const SCHEMA_DIR = path.join(REPO, 'libs/al-web-components/schemas');
const MIGRATION = path.join(REPO, '.altitude/migration.json');
const OUT = path.join(SCHEMA_DIR, 'INDEX.md');

function main() {
  const migration = JSON.parse(fs.readFileSync(MIGRATION, 'utf8'));
  const schemas = fs.readdirSync(SCHEMA_DIR).filter((f) => f.endsWith('.schema.json')).sort();
  const tagToSchema = new Map();
  for (const f of schemas) {
    const data = JSON.parse(fs.readFileSync(path.join(SCHEMA_DIR, f), 'utf8'));
    tagToSchema.set(data.altitude.tagName, f);
  }

  const lines = [
    '# Component schema index',
    '',
    'Generated by `scripts/generate-schema-index.js`. Do not hand-edit.',
    'Each row maps a migration-tracked component to its T3.2 JSON Schema.',
    'The schemas are consumed by the T3.4 contract validator.',
    '',
    '| Component | State | Class | Schema |',
    '|---|---|---|---|',
  ];

  for (const [name, entry] of Object.entries(migration.components || {}).sort()) {
    const expectedTag = `al-${name}`;
    const schemaFile = tagToSchema.get(expectedTag);
    if (!schemaFile) {
      lines.push(`| \`${name}\` | ${entry.state} | _missing_ | _no schema — investigate_ |`);
      continue;
    }
    const schema = JSON.parse(fs.readFileSync(path.join(SCHEMA_DIR, schemaFile), 'utf8'));
    lines.push(
      `| \`${name}\` | ${entry.state} | ${schema.altitude.className} | [\`${schemaFile}\`](./${schemaFile}) |`
    );
  }

  fs.writeFileSync(OUT, lines.join('\n') + '\n');
  console.log(`[schema-index] wrote ${Object.keys(migration.components).length} entries → ${path.relative(REPO, OUT)}`);
}

main();
