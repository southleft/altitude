#!/usr/bin/env node
/**
 * T1.1 extension — emit a TypeScript type union of every `--al-*` token name
 * plus an alias map. Consumers can `import type { AltitudeTokenName } …`
 * and the contract validator (T3.4) can lift it for token-ref checks.
 *
 * Inputs:  libs/al-web-components/styles/dist-v5/tokens.json
 * Outputs:
 *   - libs/al-web-components/styles/dist-v5/tokens.d.ts
 *   - libs/al-web-components/styles/dist-v5/aliases.json
 *
 * The alias map is frozen at this build so downstream code can rely on
 * stable names through T6.4. Today every alias is a no-op (`{name}` →
 * `{name}`), which is the "freeze before drift" snapshot the plan wants.
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const REPO = path.resolve(__dirname, '..');
const V5 = path.join(REPO, 'libs/al-web-components/styles/dist-v5');
const TOKENS_JSON = path.join(V5, 'tokens.json');

function main() {
  if (!fs.existsSync(TOKENS_JSON)) {
    console.error('[token-types] missing input — run build:tokens first.');
    process.exit(1);
  }
  const flat = JSON.parse(fs.readFileSync(TOKENS_JSON, 'utf8'));
  const names = Object.keys(flat).sort();

  // tokens.d.ts — union of names + a typed lookup table.
  const dts = [
    '// AUTO-GENERATED by scripts/emit-token-types.js. Do not edit.',
    '// Source: dist-v5/tokens.json (the v5 pipeline\'s flat JSON output).',
    '',
    'export type AltitudeTokenName =',
    ...names.map((n, i) => `  | '${n}'${i === names.length - 1 ? ';' : ''}`),
    '',
    'export type AltitudeTokenMap = {',
    ...names.map((n) => `  '${n}': string;`),
    '};',
    '',
    'export declare const altitudeTokens: AltitudeTokenMap;',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(V5, 'tokens.d.ts'), dts);

  // aliases.json — frozen at T1.1, identity map. Entries can later be
  // updated as renames land (with the migration manifest's compatBudget).
  const aliases = {
    $schema: 'https://southleft.com/altitude/aliases.schema.json',
    frozenAt: 'T1.1',
    deprecateBy: '3.0.0',
    aliases: Object.fromEntries(names.map((n) => [n, n])),
  };
  fs.writeFileSync(path.join(V5, 'aliases.json'), JSON.stringify(aliases, null, 2) + '\n');

  console.log(`[token-types] wrote ${names.length} token names → tokens.d.ts + aliases.json`);
}

main();
